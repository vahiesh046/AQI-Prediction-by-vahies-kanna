# Step 5: Filter city data
city_df = df[df['City'].str.lower() == city_input.lower()].sort_values('Date')

if len(city_df) < 10:
    print(f"\n❌ Invalid city name Not enough data for '{city_input}'. Try another city.")
else:
    # Step 6: Prepare AQI with lags
    aqi_df = city_df[['Date', 'AQI']].copy()
    aqi_df['AQI_1'] = aqi_df['AQI'].shift(1)
    aqi_df['AQI_2'] = aqi_df['AQI'].shift(2)
